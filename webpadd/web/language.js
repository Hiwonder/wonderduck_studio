const SKIP_TAGS = new Set(['SCRIPT', 'STYLE', 'SVG', 'PATH', 'CODE', 'PRE']);
const USER_CONTENT = '#network-list strong, #models-path, #control-action-options [role="option"]';
const USER_OPTIONS = '#action-groups, #action-select-name, #color-presets';
const textOriginal = new WeakMap();
const attributeOriginal = new WeakMap();
const listeners = new Set();
let language = 'zh';
let observer;

function savedLanguage() {
  const requested = new URLSearchParams(location.search).get('lang');
  if (requested === 'en' || requested === 'zh') return requested;
  try { return localStorage.getItem(STORAGE_KEY) === 'en' ? 'en' : 'zh'; } catch { return 'zh'; }
}

export function getLanguage() { return language; }

export function translate(value) {
  if (language !== 'en' || typeof value !== 'string' || !/[\u4e00-\u9fff]/.test(value)) return value;
  const direct = ENGLISH.get(value);
  if (direct !== undefined) return direct;
  for (const [pattern, render] of DYNAMIC) {
    const match = value.match(pattern);
    if (match) return render(...match);
  }
  for (const [prefix, translated] of MESSAGE_PREFIXES) {
    for (const separator of ['：', ': ']) {
      const marker = `${prefix}${separator}`;
      if (value.startsWith(marker)) return `${translated}: ${translate(value.slice(marker.length))}`;
    }
  }
  return value;
}

export function translateServoStatus(value) {
  return language === 'en' && value === '关闭' ? 'Off' : translate(value);
}

// Polling code may render an already translated value. Keep its source beside
// the text node so switching back to Chinese does not depend on another poll.
export function setLocalizedText(element, value, servoStatus = false) {
  const original = String(value);
  const rendered = servoStatus ? translateServoStatus(original) : translate(original);
  if (element.textContent !== rendered) element.textContent = rendered;
  const node = element.firstChild;
  if (node && node.nodeType === Node.TEXT_NODE && !node.nextSibling) {
    textOriginal.set(node, { original, rendered, servoStatus });
  }
}

export function setLocalizedAttribute(element, name, value, servoStatus = false) {
  const original = String(value);
  const rendered = servoStatus ? translateServoStatus(original) : translate(original);
  if (element.getAttribute(name) !== rendered) element.setAttribute(name, rendered);
  let originals = attributeOriginal.get(element);
  if (!originals) { originals = new Map(); attributeOriginal.set(element, originals); }
  originals.set(name, { original, rendered, servoStatus });
}

export function sourceText(element) {
  const walker = document.createTreeWalker(element, NodeFilter.SHOW_TEXT);
  let value = '', node;
  while ((node = walker.nextNode())) {
    const previous = textOriginal.get(node);
    const original = previous && node.nodeValue === previous.rendered ? previous.original : node.nodeValue;
    value += CHINESE.get(original) || original;
  }
  return value;
}

function excluded(element, value, attribute = false) {
  if (!element || SKIP_TAGS.has(element.tagName) || element.isContentEditable || element.closest('[data-i18n-skip]')) return true;
  if (!attribute && ['INPUT', 'TEXTAREA'].includes(element.tagName)) return true;
  if (element.closest(USER_CONTENT)) return true;
  if (element.id === 'models-filename' && document.getElementById('models-file')?.files.length) return true;
  if (element.tagName === 'OPTION' && element.closest(USER_OPTIONS) && element.value) return true;
  if (['network-current', 'network-ap-name'].includes(element.id) && !['--', '未连接', '未读取', 'Disconnected', 'Not read'].includes(value.trim())) return true;
  if (element.id === 'control-action-name' && !['选择动作', 'Select action'].includes(value.trim())) return true;
  return false;
}

function localized(value) {
  const trimmed = value.trim();
  if (!trimmed) return value;
  const result = translate(trimmed);
  if (result === trimmed) return value;
  const start = value.indexOf(trimmed);
  return value.slice(0, start) + result + value.slice(start + trimmed.length);
}

function updateText(node) {
  const current = node.nodeValue;
  if (!current || excluded(node.parentElement, current)) return;
  const previous = textOriginal.get(node);
  const original = previous && current === previous.rendered ? previous.original : current;
  const servoStatus = previous && current === previous.rendered && previous.servoStatus === true;
  if (node.parentElement.tagName === 'OPTION' && !node.parentElement.hasAttribute('value')) {
    // An option without a value uses its text as its value. Preserve the
    // protocol value before changing the visible label.
    if (localized(original) !== original) node.parentElement.setAttribute('value', node.parentElement.value);
  }
  const rendered = language === 'en' ? (servoStatus ? translateServoStatus(original) : localized(original)) : original;
  textOriginal.set(node, { original, rendered, servoStatus });
  if (current !== rendered) node.nodeValue = rendered;
}

function updateAttribute(element, name) {
  const current = element.getAttribute(name);
  if (!current || excluded(element, current, true)) return;
  let originals = attributeOriginal.get(element);
  if (!originals) { originals = new Map(); attributeOriginal.set(element, originals); }
  const previous = originals.get(name);
  const original = previous && current === previous.rendered ? previous.original : current;
  const servoStatus = previous && current === previous.rendered && previous.servoStatus === true;
  const rendered = language === 'en' ? (servoStatus ? translateServoStatus(original) : localized(original)) : original;
  originals.set(name, { original, rendered, servoStatus });
  if (current !== rendered) element.setAttribute(name, rendered);
}

function updateTree(root) {
  if (root.nodeType === Node.TEXT_NODE) { updateText(root); return; }
  if (root.nodeType !== Node.ELEMENT_NODE && root.nodeType !== Node.DOCUMENT_NODE) return;
  if (root.nodeType === Node.ELEMENT_NODE && excluded(root, root.textContent || '', true)) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
  let node = root;
  while (node) {
    if (node.nodeType === Node.TEXT_NODE) updateText(node);
    else if (node.nodeType === Node.ELEMENT_NODE && !excluded(node, node.textContent || '', true)) {
      for (const name of ['title', 'aria-label', 'aria-description', 'aria-valuetext', 'placeholder', 'alt']) updateAttribute(node, name);
    }
    node = walker.nextNode();
  }
}

export function setLanguage(next, { persist = true } = {}) {
  if (next !== 'zh' && next !== 'en') return;
  language = next;
  document.documentElement.lang = next === 'en' ? 'en' : 'zh-CN';
  if (persist) { try { localStorage.setItem(STORAGE_KEY, next); } catch { /* Preference remains active for this page. */ } }
  if (document.body) updateTree(document.body);
  for (const listener of listeners) listener(next);
  window.dispatchEvent(new CustomEvent('studio-language-change', { detail: next }));
}

export function onLanguageChange(listener) {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

function start() {
  language = savedLanguage();
  setLanguage(language, { persist: false });
  observer = new MutationObserver(records => {
    for (const record of records) {
      if (record.type === 'characterData') updateText(record.target);
      else if (record.type === 'attributes') updateAttribute(record.target, record.attributeName);
      else for (const node of record.addedNodes) updateTree(node);
    }
  });
  observer.observe(document.body, { subtree: true, childList: true, characterData: true,
    attributes: true, attributeFilter: ['title', 'aria-label', 'aria-description', 'aria-valuetext', 'placeholder', 'alt'] });
}

window.WonderduckLanguage = { getLanguage, setLanguage, translate, translateServoStatus, setLocalizedText, sourceText, onLanguageChange };
window.addEventListener('storage', event => {
  if (event.key === STORAGE_KEY && (event.newValue === 'zh' || event.newValue === 'en')) {
    setLanguage(event.newValue, { persist: false });
  }
});
window.addEventListener('message', event => {
  if (window.parent === window || event.source !== window.parent || event.data?.type !== 'studio-language') return;
  try {
    const parent = new URL(event.origin);
    if (parent.protocol !== location.protocol || parent.hostname !== location.hostname) return;
    if (document.referrer && new URL(document.referrer).origin !== event.origin) return;
  } catch { return; }
  setLanguage(event.data.language);
});
if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', start, { once: true });
else start();
